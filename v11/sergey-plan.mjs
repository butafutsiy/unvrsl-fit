export function createSergeyPlan(now=Date.now()){
  return {
    id:SEED_ID,seedId:SEED_ID,sourceRevision:2,name:PLAN_NAME,author:'Сергей',
    description:'8-недельный сплит 3 раза в неделю. Рабочий вес подбирается по целевому RPE.',created:now,updated:now,
    weeks:WEEK_META.map(([focus,rpe],weekIndex)=>({n:weekIndex+1,focus,days:DAYS.map(([name,definitions],dayIndex)=>({
      id:`sergey-w${weekIndex+1}-d${dayIndex+1}`,name,
      ex:definitions.map(([exerciseName,type,note],exerciseIndex)=>{
        const [count,reps,repLabel,tempo,rest]=SCHEMES[type][weekIndex];
        return {id:`sergey-w${weekIndex+1}-d${dayIndex+1}-e${exerciseIndex+1}`,n:exerciseName,sourceId:null,method:'STANDARD',rpe,tempo,rest,note:note||'',repLabel,sets:Array.from({length:count},()=>({w:0,r:reps,rest}))};
      })
    }))}))
  };
}

export function ensureSergeyPlan(state,now=Date.now()){
  if(!Array.isArray(state.programs))state.programs=[];
  const existing=state.programs.find(program=>program?.seedId===SEED_ID||program?.id===SEED_ID||program?.name===PLAN_NAME);
  if(existing)return false;
  state.programs.push(createSergeyPlan(now));
  state.updatedAt=now;
  return true;
}
