"""Rebuild the reviewed USDA SR28 subset from the official archive.
Usage: python scripts/import-nutrition.py /absolute/path/sr28asc.zip
No network, guessed nutrients, or duplicate inserts. Source IDs are permanent.
"""
import csv, hashlib, json, re, sys, zipfile
from pathlib import Path

root = Path(__file__).resolve().parents[1]
archive = Path(sys.argv[1])
z = zipfile.ZipFile(archive)
def table(name):
    return csv.reader(z.read(name).decode('latin1').splitlines(), delimiter='^', quotechar='~')
names = {r[0]: r for r in table('FOOD_DES.txt')}
values = {}
for r in table('NUT_DATA.txt'):
    if r[1] in ('203','204','205','208','291','221'):
        values.setdefault(r[0], {})[{'203':'p','204':'f','205':'c','208':'k','291':'fiber','221':'alcohol'}[r[1]]] = float(r[2])
review = json.loads((root/'data/nutrition/usda-selection.json').read_text())
foods = {}
for code, item in review.items():
    row = names[code]; n = values.get(code,{})
    item = dict(item); low = row[2].lower(); allergens=set(item.get('allergens',[]))
    for pattern,allergen in [(r'\begg\b','egg'),(r'peanut','peanuts'),(r'soy|tofu|tempeh','soy'),(r'sesame','sesame'),(r'mustard','mustard'),(r'celery|celeriac','celery')]:
        if re.search(pattern,low): allergens.add(allergen)
    item['allergens']=sorted(allergens)
    item['allergensUncertain']=item['category'] in ('bread','sauce','sweet') or code in ('11583','16158','16098')
    if item['state']=='raw' and low.startswith('crustaceans, shrimp') and 'not previously frozen' in low:item['name']='Креветка, сырая (до заморозки)'
    elif item['state']=='raw' and low.startswith('crustaceans, shrimp') and 'may have been previously frozen' in low:item['name']='Креветка, сырая (возможно, после заморозки)'
    if any(k not in n for k in ('k','p','f','c')):
        raise ValueError('Missing nutrients for '+code)
    if any(n[k]<0 for k in n) or n['k']>1000 or n['p']+n['f']+n['c']>100.5:
        raise ValueError('Invalid nutrients for '+code)
    foods['sr28-'+code] = {**item, **n, 'unit':'g', 'basisGrams':100,
        'fatPer100g':n['f'], 'nutritionQuality':'reference',
        'carbohydrateDefinition':'total_including_fiber',
        'sourceInfo':{'provider':'USDA SR28','code':code,'originalName':row[2],
        'url':'https://www.ars.usda.gov/ARSUserFiles/80400525/Data/SR/SR28/dnload/sr28asc.zip',
        'license':'Public domain','release':'SR28 (2015, revised 2016)'},
        'energyMethod':'Published source energy; specific Atwater factors may differ from 4/9/4'}
if len({x['name'] for x in foods.values()}) != len(foods):
    raise ValueError('Duplicate translated descriptions')
payload = json.dumps(foods,ensure_ascii=False,separators=(',',':'))
(root/'nutrition-foods-data.js').write_text("'use strict';\n// Generated by scripts/import-nutrition.py. See data/nutrition/SOURCES.md.\n(function(root){const foods="+payload+";if(typeof module==='object'&&module.exports)module.exports=foods;else root.UNVRSLVerifiedFoods=foods;})(typeof window==='object'?window:globalThis);\n")
(root/'data/nutrition/import-manifest.json').write_text(json.dumps({'archiveSHA256':hashlib.sha256(archive.read_bytes()).hexdigest(),'foodDescriptionsSHA256':hashlib.sha256(z.read('FOOD_DES.txt')).hexdigest(),'nutrientDataSHA256':hashlib.sha256(z.read('NUT_DATA.txt')).hexdigest(),'count':len(foods),'missingNutrients':0,'duplicateNames':0},indent=2)+'\n')
print('Verified reference foods:',len(foods))
